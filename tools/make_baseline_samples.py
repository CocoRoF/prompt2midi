"""Rebuild data/samples/baseline-v0/: the sample set, the MIDI files the RuleProvider writes for it, and the README listing.

    python tools/make_baseline_samples.py [--commit HASH]     (run from the repository root)

Offline: RuleProvider only, no network, no keys, no holdout set, no external data. The MIDI files are a frozen snapshot
("baseline v0"): they are NOT regenerated by the tests, so a later change to the rules or the compiler does not break the
build; run this script on purpose to make a new baseline (and name it baseline-v1).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from prompt2midi.pipeline import generate  # noqa: E402
from prompt2midi.providers import RuleProvider  # noqa: E402

OUT = ROOT / "data" / "samples" / "baseline-v0"
RESEARCH = ROOT / "data" / "eval_prompts_research1.json"   # 연구 1팀 English prompts (10)
SMOKE = ROOT / "tests" / "fixtures" / "smoke_set.json"      # development smoke set (20)
SMOKE_PICK = ["s07", "s08", "e03", "e06", "e07", "e09"]     # jazz (ko), dark film (ko), lo-fi, bossa nova, electronic dance, blues shuffle


def build_set() -> dict:
    prompts = []
    for p in json.loads(RESEARCH.read_text(encoding="utf-8")):
        tonic, mode = p["key"].split(" ", 1)
        prompts.append({"id": f"r{p['id']:02d}", "lang": "en", "tier": "A", "text": p["text"],
                        "expect": {"tonic": tonic, "mode": mode, "tempo_bpm": p["bpm"]}})
    smoke = {p["id"]: p for p in json.loads(SMOKE.read_text(encoding="utf-8"))["prompts"]}
    prompts += [smoke[i] for i in SMOKE_PICK]
    return {"version": "1", "name": "baseline-v0 samples (연구 1팀 영어 10 + smoke 6)", "prompts": prompts}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--commit", help="commit hash to record (default: git rev-parse --short HEAD)")
    args = ap.parse_args(argv)
    commit = args.commit or subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    eval_set = build_set()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "set.json").write_text(json.dumps(eval_set, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rows = []
    for p in eval_set["prompts"]:
        res = generate(p["text"], provider=RuleProvider(), fallback=False)
        (OUT / f"{p['id']}.mid").write_bytes(res.midi)
        rows.append((p["id"], p["lang"], p["text"], hashlib.sha256(res.midi).hexdigest()[:8], len(res.midi)))
    lines = [
        "# baseline-v0 샘플 MIDI", "",
        f"- 생성: `python tools/make_baseline_samples.py` · 생성 시점 코드 커밋 `{commit}` (RuleProvider, 폴백 없음, 시드는 사양의 것)",
        "- 프롬프트: 연구 1팀 영어 10개(`data/eval_prompts_research1.json`, id `r01`~`r10`) + 개발용 smoke 세트(`tests/fixtures/smoke_set.json`)에서 장르·무드가 고르게 섞이게 6개. 파일명 = 프롬프트 id.",
        "- 보류 세트·외부 데이터·LLM·키 없음. 이 MIDI 는 **동결된 기준선**이다: 테스트는 다시 생성해 비교하지 않는다. 규칙·컴파일러를 바꿔 다시 만들 때는 `baseline-v1` 처럼 새 폴더로 둔다.",
        "- `set.json` 은 같은 목록을 평가 세트 형식으로 적은 것이다: `python -m prompt2midi.evalkit data/samples/baseline-v0/set.json --provider rule`.",
        "- 이 파일들의 표현력 대리 지표 값과 해석: `docs/baseline-expressiveness-v0.md` (값은 음악 품질이 아니다).", "",
        "| id | 언어 | 프롬프트 | MIDI sha256(앞 8자) | 바이트 |", "|---|---|---|---|---|",
    ]
    lines += [f"| `{i}` | {lang} | {text} | `{sha}` | {size} |" for i, lang, text, sha, size in rows]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} samples -> {OUT} (commit {commit})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
